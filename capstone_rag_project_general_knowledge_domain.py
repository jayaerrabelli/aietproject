qdrant_path = '/content/RAG_Project/qdrant_db'
client = QdrantClient(path=qdrant_path)
hybrid_collection_name = "ragbench_hybrid"

if client.collection_exists(hybrid_collection_name):
    print(f"⚠️ Collection '{hybrid_collection_name}' already exists. Deleting it to start fresh...")
    client.delete_collection(hybrid_collection_name)

client.create_collection(
    collection_name=hybrid_collection_name,
    vectors_config={
        "dense": VectorParams(size=dense_model.get_embedding_dimension(), distance=Distance.COSINE)
    },
    sparse_vectors_config={
        "sparse": SparseVectorParams()
    }
)
print(f"✅ Created Hybrid Qdrant collection: '{hybrid_collection_name}'")

# 3. Load text chunks
chunked_save_path = '/content/RAG_Project/chunked_docs.json'
with open(chunked_save_path, 'r', encoding='utf-8') as f:
    all_chunks = json.load(f)

texts = [chunk['text'] for chunk in all_chunks]

# 4. Generate Embeddings (Dense + Sparse)
print(f"\n⚡ Generating Dense vectors for {len(texts)} chunks...")
dense_embs = dense_model.encode(texts, batch_size=2048, show_progress_bar=True)

print("\n⚡ Generating Sparse vectors for all chunks... (This may take a minute)")
sparse_embs = list(sparse_model.embed(texts, batch_size=2048))

# 5. Batch Upload to Qdrant
upsert_batch_size = 5000
print(f"\n💾 Uploading vectors to Qdrant (Batch size: {upsert_batch_size})...")

for i in range(0, len(all_chunks), upsert_batch_size):
    batch_chunks = all_chunks[i : i + upsert_batch_size]
    batch_dense = dense_embs[i : i + upsert_batch_size]
    batch_sparse = sparse_embs[i : i + upsert_batch_size]

    points = []
    for j, (chunk, d_emb, s_emb) in enumerate(zip(batch_chunks, batch_dense, batch_sparse)):
        payload = {
            "doc_id": chunk["doc_id"],
            "domain": chunk["domain"],
            "text": chunk["text"]
        }

        vector_dict = {
            "dense": d_emb.tolist(),
            "sparse": {
                "indices": s_emb.indices.tolist(),
                "values": s_emb.values.tolist()
            }
        }

        points.append(PointStruct(id=i+j, vector=vector_dict, payload=payload))

    client.upsert(collection_name=hybrid_collection_name, points=points)
    print(f"Uploaded {min(i+upsert_batch_size, len(all_chunks))} / {len(all_chunks)} records.")

print("\n✅ SUCCESS: Hybrid Database population complete!")

