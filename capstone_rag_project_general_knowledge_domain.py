from qdrant_client.models import Prefetch, FusionQuery, Fusion

hybrid_collection_name = "ragbench_hybrid"

def hybrid_retrieve_context(query_text, top_k=30):
    """
    Performs a Hybrid Search using Reciprocal Rank Fusion (RRF).
    Retrieves top_k using dense, top_k using sparse, and fuses the results.
    """
    # 1. Embed query into Dense and Sparse representations
    dense_query = dense_model.encode(query_text).tolist()
    sparse_query = next(sparse_model.embed([query_text])) # Get the single sparse embedding

    # 2. Perform Hybrid Query with Qdrant
    response = client.query_points(
        collection_name=hybrid_collection_name,
        prefetch=[
            Prefetch(
                query=dense_query,
                using="dense",
                limit=top_k
            ),
            Prefetch(
                query={
                    "indices": sparse_query.indices.tolist(),
                    "values": sparse_query.values.tolist()
                },
                using="sparse",
                limit=top_k
            )
        ],
        query=FusionQuery(fusion=Fusion.RRF),
        limit=top_k
    )

    return response.points if hasattr(response, 'points') else response

def get_ground_truth(query):
    """Helper to fetch the ground truth response from the loaded dataset."""
