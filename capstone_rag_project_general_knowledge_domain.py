def generate_answer(query_text, domain_filter=None, debug=False):
    """
    Full RAG pipeline with Re-ranking: Retrieves context from Qdrant, re-ranks with CrossEncoder,
    and generates an answer using Gemini.
    Note: domain_filter parameter is ignored as it was removed from the retrieval pipeline.
    """
    if not client_llm:
        return "Error: LLM client not initialized. Check your API key.", []

    # 1. Retrieve a larger pool of context (top 100 - Narrow and Deep) from Qdrant using Hybrid Search
    print(f"🔍 Retrieving top 100 initial contexts for query: '{query_text}'...")
    initial_results = hybrid_retrieve_context(query_text, top_k=100)

    if not initial_results:
        return "No relevant context found in the database.", []

    # 2. Re-rank using Cross-Encoder
    print("⚖️ Re-ranking 100 results using Cross-Encoder...")
    pairs = [[query_text, res.payload['text']] for res in initial_results]
    scores = cross_encoder.predict(pairs)

    # Sort results by the cross-encoder scores (descending)
    ranked_indices = np.argsort(scores)[::-1]

    # Take the top 5 after re-ranking
    top_k_reranked = 5
    best_indices = ranked_indices[:top_k_reranked]
    final_results = [initial_results[i] for i in best_indices]

    # 3. Format the context for the LLM
    context_texts = []
    for i, res in enumerate(final_results):
        context_texts.append(f"Document [{i+1}]: {res.payload['text']}")

    formatted_context = "\n\n".join(context_texts)

    # DIAGNOSTIC: Print the context being fed to the LLM
    if debug:
        print("\n" + "="*60)
        print("🛠️ DIAGNOSTIC: Top 5 Re-ranked Contexts Provided to LLM")
        print("="*60)
        print(formatted_context)
        print("="*60 + "\n")

    # 4. Construct the prompt with relaxed grounding instructions
    prompt = f"""
    You are an expert assistant for a highly specialized RAG system.
    Answer the user's question accurately using the provided context chunks.
    - Synthesize information across the chunks if the answer is split.
    - Ignore minor typos in the question (e.g., spelling of names/words) when mapping them to the context.
    - Only if the context is completely irrelevant to the question, reply with "I don't have enough information to answer that based on the provided context."

    Context:
    {formatted_context}

    Question: {query_text}

    Answer:
    """

    # 5. Generate the answer
    print("🧠 Generating answer using Gemini...")
    response = client_llm.models.generate_content(
        model='gemini-3.8-flash',
        contents=prompt,
    )

    return response.text, final_results

