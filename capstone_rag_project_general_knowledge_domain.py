for row in tqdm(subset, desc="Generating Answers"):
    new_row = {}
    for col in template_columns:
        col_lower = str(col).lower()
        # Explicitly matching template columns to dataset fields
        if col_lower == 'id':
            new_row[col] = row.get('id', '')
        elif 'question' in col_lower:
            new_row[col] = row.get('question', '')
        elif 'dataset result' in col_lower:
            # Ground truth goes here
            new_row[col] = row.get('response', '')
        elif 'returned result' in col_lower:
            # Run the RAG pipeline to generate the answer
            question = row.get('question', '')

            # Retry mechanism for Rate Limits (429 RESOURCE_EXHAUSTED)
            max_retries = 5
            for attempt in range(max_retries):
                try:
                    with io.capture_output() as captured:
                        answer, _ = generate_answer(question, debug=False)
                    new_row[col] = answer
                    break # Success, break out of retry loop
                except Exception as e:
                    if '429' in str(e) or 'RESOURCE_EXHAUSTED' in str(e):
                        if attempt < max_retries - 1:
                            sleep_time = 15 * (attempt + 1) # Incremental backoff
                            print(f"Rate limited. Waiting {sleep_time}s...")
                            time.sleep(sleep_time)
                        else:
                            new_row[col] = f"Error: {e}"
                    else:
                        new_row[col] = f"Error: {e}"
                        break # Break on non-rate-limit errors
            time.sleep(4) # Base delay of 4 seconds to stay under 15 RPM
        else:
            new_row[col] = ''

    data_to_export.append(new_row)

