evaluation_model = SentenceTransformer(EMBEDDING_MODEL_NAME)

def extract_sentence_candidates(documents_sentences):
    candidates = []

    if not isinstance(documents_sentences, (list, tuple)):
        return candidates

    for document in documents_sentences:
        if not isinstance(document, (list, tuple)):
            continue

        for sentence in document:
            if isinstance(sentence, (list, tuple)) and len(sentence) >= 2:
                sentence_key = str(sentence[0])
                sentence_text = str(sentence[1]).strip()

                if sentence_text:
                    candidates.append((sentence_key, sentence_text))

    return candidates


def evaluate_hybrid_row(row, k=5):
    candidates = extract_sentence_candidates(row["documents_sentences"])
    gold_keys = set(str(key) for key in row["all_relevant_sentence_keys"])

    if not candidates or not gold_keys:
        return None

    question = str(row["question"])
    candidate_texts = [item[1] for item in candidates]

    question_embedding = evaluation_model.encode(
        question,
        convert_to_tensor=True,
        normalize_embeddings=True
    )

    candidate_embeddings = evaluation_model.encode(
        candidate_texts,
        convert_to_tensor=True,
        normalize_embeddings=True
    )

    dense_scores = util.cos_sim(
        question_embedding,
        candidate_embeddings
    )[0].cpu().numpy()

    dense_order = np.argsort(dense_scores)[::-1][:50]

    candidate_tokens = [tokenize_text(text) for text in candidate_texts]
    candidate_bm25 = BM25Okapi(candidate_tokens)
    sparse_scores = candidate_bm25.get_scores(tokenize_text(question))
    sparse_order = np.argsort(sparse_scores)[::-1][:50]

    rrf = {}

    for rank, candidate_index in enumerate(dense_order, start=1):
        candidate_index = int(candidate_index)
        rrf[candidate_index] = rrf.get(candidate_index, 0.0) + 1 / (60 + rank)

    for rank, candidate_index in enumerate(sparse_order, start=1):
        candidate_index = int(candidate_index)
        rrf[candidate_index] = rrf.get(candidate_index, 0.0) + 1 / (60 + rank)

    ranked_indices = sorted(
        rrf,
        key=rrf.get,
        reverse=True
    )[:k]

    retrieved_keys = [candidates[index][0] for index in ranked_indices]
    hits = set(retrieved_keys).intersection(gold_keys)

    precision = len(hits) / len(retrieved_keys) if retrieved_keys else 0.0
    recall = len(hits) / len(gold_keys) if gold_keys else 0.0

    hit_ranks = [
        rank for rank, key in enumerate(retrieved_keys, start=1)
        if key in gold_keys
    ]
    mrr = 1 / hit_ranks[0] if hit_ranks else 0.0

    return {
        "precision_at_5": precision,
        "recall_at_5": recall,
        "mrr": mrr
    }


