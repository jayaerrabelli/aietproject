def hybrid_retrieve(query, dense_k=50, sparse_k=50, top_k=10, rrf_constant=60):
    dense_count = min(dense_k, collection.count())

    dense_output = collection.query(
        query_texts=[query],
        n_results=dense_count,
        include=["documents", "metadatas", "distances"]
    )

    dense_ids = dense_output["ids"][0]

    sparse_scores = bm25.get_scores(tokenize_text(query))
    sparse_indices = np.argsort(sparse_scores)[::-1][:min(sparse_k, len(all_chunks))]

    rrf_scores = {}

    for rank, chunk_id in enumerate(dense_ids, start=1):
        rrf_scores[chunk_id] = rrf_scores.get(chunk_id, 0.0) + (
            1.0 / (rrf_constant + rank)
        )

    for rank, chunk_index in enumerate(sparse_indices, start=1):
        chunk_id = all_chunk_ids[int(chunk_index)]
        rrf_scores[chunk_id] = rrf_scores.get(chunk_id, 0.0) + (
            1.0 / (rrf_constant + rank)
        )

    ranked_items = sorted(
        rrf_scores.items(),
        key=lambda item: item[1],
        reverse=True
    )[:top_k]

    results = []

    for chunk_id, rrf_score in ranked_items:
        position = chunk_id_to_position[chunk_id]
        results.append({
            "id": chunk_id,
            "text": all_chunks[position],
            "metadata": all_chunk_metadata[position],
            "rrf_score": float(rrf_score)
        })

    return results


