def normalize_documents(value):
    if value is None:
        return []

    if isinstance(value, str):
        try:
            value = json.loads(value)
        except Exception:
            value = [value]

    if not isinstance(value, (list, tuple)):
        value = [value]

    cleaned = []
    for item in value:
        if item is not None:
            text = str(item).strip()
            if text:
                cleaned.append(text)

    return cleaned


