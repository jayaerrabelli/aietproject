# Initialize BM25 on the chunked documents for sparse search
tokenized_corpus = [doc.page_content.lower().split(" ") for doc in chunked_documents]
bm25 = BM25Okapi(tokenized_corpus)

def retrieve_optimal_context(query_text, first_stage_k=15, final_k=3):
    """
    Retrieves candidate compact chunks using a hybrid combination of:
    1. Dense Search (via Cosine Similarity using Chroma vector store)
    2. Sparse Search (via BM25 Okapi)
    No neural Cross-Encoder is used.
    """
    # Dense retrieval (Chroma defaults to L2 or Cosine based on embedding model settings; similarity_search returns top matches)
    dense_results = vectorstore.similarity_search(query_text, k=final_k)
    dense_texts = [doc.page_content for doc in dense_results]

    # Sparse retrieval (BM25)
    tokenized_query = query_text.lower().split(" ")
    bm25_scores = bm25.get_scores(tokenized_query)
    top_bm25_indices = np.argsort(bm25_scores)[::-1][:final_k]
    sparse_texts = [chunked_documents[idx].page_content for idx in top_bm25_indices]

    # Combine the top results from both methods preserving order/diversity
    combined_results = []
    for d, s in zip(dense_texts, sparse_texts):
        if d not in combined_results:
            combined_results.append(d)
        if s not in combined_results:
            combined_results.append(s)

    # Return exactly the top final_k combined contexts
    return combined_results[:final_k]

