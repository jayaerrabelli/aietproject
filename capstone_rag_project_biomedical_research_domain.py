def generate_answer_groq(query_text):
    """
    Runs the complete RAG Pipeline:
    1. Retrieves top candidate contexts using our hybrid search pipeline.
    2. Safely initializes Groq and calls the qwen/qwen3.8-27b model to generate the medical answer.
    """
    global client
    retrieved_contexts = retrieve_optimal_context(query_text, first_stage_k=15, final_k=3)

    if not retrieved_contexts:
        return "Unable to retrieve context for this question.", []

    # Combine contexts into a structured prompt
    context_block = "\n\n".join([f"[Context {i+1}]: {text}" for i, text in enumerate(retrieved_contexts)])

    system_instruction = "You are a precise medical assistant. Synthesize the provided medical contexts to answer the question accurately. If the answer cannot be found in the contexts, state that clearly."
    prompt = f"Contexts:\n{context_block}\n\nQuestion: {query_text}\n\nAnswer:"

    # Dynamic/Lazy initialization of Groq Client
    if 'client' not in globals() or client is None:
        try:
            from groq import Groq
            from google.colab import userdata
            api_key = userdata.get('GROQ_API_KEY')
            client = Groq(api_key=api_key)
        except Exception as e:
            return f"Authentication Error: Please set 'GROQ_API_KEY' in the Colab secrets manager (🔑 tab) and make sure it has notebook access.", retrieved_contexts

    try:
        chat_completion = client.chat.completions.create(
            messages=[
                {"role": "system", "content": system_instruction},
                {"role": "user", "content": prompt}
            ],
            model="qwen/qwen3.8-27b",
            temperature=0.0,
            max_tokens=300
        )
        return chat_completion.choices[0].message.content, retrieved_contexts
    except Exception as e:
        return f"Generation Error: {e}", retrieved_contexts

