def calculate_token_metrics(generated, ground_truth):
    """
    Calculates simple token-level (word) Precision, Recall, and F1-score.
    """
    gen_tokens = str(generated).lower().split()
    gt_tokens = str(ground_truth).lower().split()

    if not gen_tokens or not gt_tokens:
        return 0.0, 0.0, 0.0

    gen_set = set(gen_tokens)
    gt_set = set(gt_tokens)

    # Calculate overlapping common tokens
    common_tokens = gen_set.intersection(gt_set)
    overlap_count = len(common_tokens)

    precision = overlap_count / len(gen_set)
    recall = overlap_count / len(gt_set)

    if precision + recall > 0:
        f1 = 2 * (precision * recall) / (precision + recall)
    else:
        f1 = 0.0

    return precision, recall, f1

evaluation_results = []

# Evaluate only the first 5 samples
subset_samples = eval_samples #[:5]
print(f"Evaluating RAG pipeline with semantic retrieval and token-level answer metrics over {len(subset_samples)} samples...")

for idx, sample in enumerate(subset_samples):
    query_text = sample['question']
    gt = sample['ground_truth']

    # 1. Retrieve candidate context & Generate Answer via pipeline
    predicted_answer, source_contexts = generate_answer_groq(query_text)

    # 2. Evaluate Retrieval using Semantic Vector Similarity
    found_hit = False
    best_sim = 0.0

    if source_contexts:
        gt_emb = np.array(embeddings.embed_query(gt))
        context_embs = np.array(embeddings.embed_documents(source_contexts))

        norms_context = np.linalg.norm(context_embs, axis=1)
        norm_gt = np.linalg.norm(gt_emb)

        if norm_gt > 0 and (norms_context > 0).all():
            similarities = np.dot(context_embs, gt_emb) / (norms_context * norm_gt)
            best_sim = float(np.max(similarities))
            if best_sim >= 0.60:
                found_hit = True

    # 3. Compute Answer Generation Quality (Simple Token-level Precision & Recall)
    precision, recall, f1_score = calculate_token_metrics(predicted_answer, gt)

    # 4. Compile Metrics
    evaluation_results.append({
        "Index": idx + 1,
        "Question": query_text,
        "Generated Answer": predicted_answer,
        "Ground Truth Answer": gt,
        "Retrieval Best Similarity": f"{best_sim:.4f}",
        "Retrieval Hit": "Yes" if found_hit else "No",
        "Answer Precision": f"{precision:.4f}",
        "Answer Recall": f"{recall:.4f}",
        "Answer F1-Score": f"{f1_score:.4f}",
        "Source Contexts Used": "\n---\n".join(source_contexts)
    })

