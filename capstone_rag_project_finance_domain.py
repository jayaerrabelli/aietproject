from rank_bm25 import BM25Okapi
import numpy as np

def hybrid_search_rrf(query_text):
    tokenized_query = query_text.lower().split(" ")

    # 3. Dense Search (retrieve top 50 candidates to allow reranking/fusion)
    dense_results = collection.query(
        query_texts=[query_text],
        n_results=50
    )

    dense_docs = dense_results['documents'][0]
    dense_ids = dense_results['ids'][0]

    # 4. Sparse Search (BM25 scores for all chunks)
    sparse_scores = bm25.get_scores(tokenized_query)

    # 5. Hybrid Search Fusion (Reciprocal Rank Fusion - RRF)
    # Map chunk to its dense rank and sparse rank
    dense_ranks = {doc_id: rank for rank, doc_id in enumerate(dense_ids)}

    # Sort all documents by BM25 sparse score to get sparse ranks
    sparse_ranking_indices = np.argsort(sparse_scores)[::-1]
    sparse_ranks = {f"chunk_{idx}": rank for rank, idx in enumerate(sparse_ranking_indices)}

    rrf_scores = {}
    constant_k = 10 # standard RRF constant

    for i, chunk_id in enumerate(ids):
        # Dense rank (if not retrieved in top 15, assign a large rank penalty)
        dense_rank = dense_ranks.get(chunk_id, 100)
        # Sparse rank
        sparse_rank = sparse_ranks.get(chunk_id, 100)

        # RRF formula: 1 / (k + rank)
        score = (1.0 / (constant_k + dense_rank)) + (1.0 / (constant_k + sparse_rank))
        rrf_scores[chunk_id] = score

    # Sort by final RRF score
    sorted_rrf = sorted(rrf_scores.items(), key=lambda x: x[1], reverse=True)
    return sorted_rrf

