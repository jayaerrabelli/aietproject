from google import genai
from google.colab import userdata

def generate_answer(sorted_rrf):
    # Initialize the Gemini client
    try:
        GOOGLE_API_KEY = userdata.get('GOOGLE_API_KEY')
        client = genai.Client(api_key=GOOGLE_API_KEY)
    except Exception:
        client = genai.Client()

    # Extract the top 10 contexts directly from sorted_rrf (the hybrid search result)
    top_rrf_contexts = []
    for rank, (chunk_id, score) in enumerate(sorted_rrf[:10]):
        chunk_idx = int(chunk_id.split("_")[1])
        doc_text = chunks[chunk_idx]
        top_rrf_contexts.append(f"[Source: {chunk_id} | RRF Score: {score:.4f}]\n{doc_text}")

    context_str_rrf = "\n\n===\n\n".join(top_rrf_contexts)

    # Construct the final prompt for the gemini-2.5-flash-lite model (renamed from 3.5-flash-lite)
    prompt = f"""You are an expert financial assistant. Use the following hybrid search context fragments to answer the question at the end.
If you don't know the answer, say that you don't know.

Context:
{context_str_rrf}

Question: {query_text}

Answer:"""

    # Call the model
    response = client.models.generate_content(
        model='gemini-2.5-flash-lite',
        contents=prompt
    )
    return response.text

# Call the function and print the result
generated_response = generate_answer(sorted_rrf)
print("=== Generated Response (Using Raw Hybrid RRF Context) ===")
print(generated_response)

